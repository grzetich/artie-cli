"""Render analysis reports as a markdown file.

The terminal reporter draws Rich panels and box rules, which are unreadable
once they land in a `.md`. This renders the same report as real markdown --
headings, a summary table, nested lists -- so the file is legible on GitHub,
diffable across runs, and pasteable into a ticket.

Content parity with the terminal report is deliberate: same checks, same
findings, same recommendations, same generated code. Only the presentation
differs.
"""

from __future__ import annotations

import re
from datetime import datetime, timezone
from pathlib import PurePath
from urllib.parse import urlparse

from artie.checks.base import CheckResult, Severity

# Suffixes stripped from the generated filename. The extension describes the
# format artie read, not the report, and keeping it produces awkward names
# like `api-example-com-openapi.yaml.md`.
_DOC_SUFFIXES = (
    ".yaml", ".yml", ".json", ".md", ".markdown", ".html", ".htm", ".txt",
)

_SEVERITY_LABEL: dict[Severity, str] = {
    Severity.EXCELLENT: "excellent",
    Severity.GOOD: "good",
    Severity.NEEDS_WORK: "needs work",
    Severity.POOR: "poor",
    Severity.NOT_EVALUABLE: "not evaluable",
}

_SEVERITY_MARK: dict[Severity, str] = {
    Severity.EXCELLENT: "PASS",
    Severity.GOOD: "PASS",
    Severity.NEEDS_WORK: "WARN",
    Severity.POOR: "FAIL",
    Severity.NOT_EVALUABLE: "—",
}


def report_filename(target: str) -> str:
    """Build `domain-path.md` from whatever was passed to `artie check`.

    A URL contributes its host and path, so
    `https://api.example.com/v1/openapi.yaml` becomes
    `api-example-com-v1-openapi.md`.

    A local file contributes only its own name. Using the full path would make
    the report name depend on how the file was addressed -- `./openapi.yaml`
    and `/home/me/proj/openapi.yaml` are the same document and must produce
    the same report, or a second run quietly writes a second file.

    Everything is slugified to one lowercase hyphenated token so the name is
    safe on every filesystem and sorts predictably in a directory of reports.
    """
    parsed = urlparse(target)
    if parsed.scheme in ("http", "https") and parsed.netloc:
        raw = f"{parsed.netloc}{parsed.path}"
    else:
        raw = PurePath(target).name or target

    lowered = raw.lower().rstrip("/")
    for suffix in _DOC_SUFFIXES:
        if lowered.endswith(suffix):
            lowered = lowered[: -len(suffix)]
            break

    slug = re.sub(r"[^a-z0-9]+", "-", lowered).strip("-")
    # A path of all separators (e.g. "./" or "/") slugifies to nothing.
    return f"{slug or 'artie-report'}.md"


def _escape_cell(text: str) -> str:
    """Keep a pipe in a check name from breaking the summary table."""
    return text.replace("|", "\\|")


def render(
    source: str,
    format_type: str,
    results: list[CheckResult],
    format_label: str | None = None,
    content_type: str | None = None,
) -> str:
    """Render an analysis report as markdown text."""
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines: list[str] = [
        "# API Documentation AI-Readiness Report",
        "",
        f"- **Source:** `{source}`",
        f"- **Format:** {format_label or format_type}",
    ]
    if content_type:
        lines.append(f"- **Server returned:** `{content_type}`")
    lines += [f"- **Retrieved:** {timestamp}", "", "## Summary", ""]

    lines.append("| | Check | Score | Severity |")
    lines.append("|---|---|---|---|")
    for result in results:
        lines.append(
            f"| {_SEVERITY_MARK[result.severity]} "
            f"| {_escape_cell(result.name)} "
            f"| {result.score_display} "
            f"| {_SEVERITY_LABEL[result.severity]} |"
        )

    evaluable = [r for r in results if r.is_evaluable and r.score is not None]
    if evaluable:
        mean = sum(r.score for r in evaluable) / len(evaluable)
        lines += [
            "",
            f"{len(evaluable)} of {len(results)} checks evaluable; "
            f"mean score {mean:.1f}/10.",
        ]

    lines.append("")
    for result in results:
        lines += _render_detail(result)

    lines += [
        "---",
        "",
        "Generated by [artie-cli](https://github.com/grzetich/artie-cli). "
        "Based on Tokens Not Jokin' research: <https://tokensnotjokin.com>",
        "",
    ]
    return "\n".join(lines)


def _render_detail(result: CheckResult) -> list[str]:
    lines = [f"## {result.name} — {result.score_display}", ""]
    if result.description:
        lines += [f"_{result.description}_", ""]

    if result.findings:
        lines.append("**Findings**")
        lines.append("")
        for finding in result.findings:
            # Findings are pre-indented with two spaces to nest cost lines
            # under their heading in the terminal; preserve that as a sublist.
            if finding.startswith("  "):
                lines.append(f"  - {finding.strip()}")
            else:
                lines.append(f"- {finding}")
        lines.append("")

    if result.recommendations:
        lines.append("**Recommendations**")
        lines.append("")
        for rec in result.recommendations:
            lines.append(f"- {rec}")
        lines.append("")

    if not result.findings and not result.recommendations:
        lines += ["_No details._", ""]

    code = result.metadata.get("code") if result.metadata else None
    if code:
        lines += ["**Generated code**", "", "```python", code.rstrip(), "```", ""]

    baseline = result.metadata.get("baseline_code") if result.metadata else None
    if baseline:
        lines += [
            "<details><summary>Baseline code (no docs supplied)</summary>",
            "",
            "```python",
            baseline.rstrip(),
            "```",
            "",
            "</details>",
            "",
        ]
    return lines
